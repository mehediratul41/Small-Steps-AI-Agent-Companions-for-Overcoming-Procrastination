"""Generate the legacy canonical-value/error display bridge from the ARB source.

New UI should use typed context.l10n getters directly. This bridge keeps stored
research codes in English while translating their display at selected boundaries.
Run after flutter gen-l10n; never apply to participant-authored task/chat text.
"""
import json
import re
from pathlib import Path

folder = Path(__file__).resolve().parents[1] / "lib" / "l10n"
arb = json.loads((folder / "app_en.arb").read_text(encoding="utf-8"))
entries = {value: key for key, value in arb.items() if not key.startswith("@")}


def quoted(value):
    return json.dumps(value, ensure_ascii=False).replace("$", r"\$")


lines = [
    "// Generated by tool/generate-display-catalog.py from app_en.arb.",
    "import 'app_localizations.dart';",
    "String translateValue(AppLocalizations l, String value) {",
    "  if (l.localeName.startsWith('en')) return value;",
    "  value = value.replaceFirst(RegExp(r'^(FormatException|Bad state): '), '');",
    "  switch (value) {",
]
for text, key in entries.items():
    if not re.search(r"\{p\d+\}", text):
        lines.append(f"    case {quoted(text)}: return l.{key};")
lines.append("  }")
for text, key in entries.items():
    args = re.findall(r"\{p(\d+)\}", text)
    if not args or text in ["{p0}", "{p0}{p1}", "{p0} · {p1}", "{p0}:{p1}"]:
        continue
    pattern = re.escape(text)
    for arg in set(args):
        pattern = pattern.replace(re.escape("{p" + arg + "}"), "(.*?)")
    values = ", ".join(f"match.group({i+1})!" for i in range(len(args)))
    lines.append(f"  {{ final match = RegExp({quoted('^'+pattern+'$')}, dotAll: true).firstMatch(value); if (match != null) {{ return l.{key}({values}); }} }}")
lines.append("  return value;\n}")
(folder / "catalog.dart").write_text("\n".join(lines) + "\n", encoding="utf-8")
